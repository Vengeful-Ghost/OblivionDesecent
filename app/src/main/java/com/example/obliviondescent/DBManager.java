    /* ============================================================
       CO-OP LOBBIES — the document id is the join code
       ============================================================ */

    public static final int MAX_PARTY_SIZE = 4;
    public static final int LOBBY_CODE_LENGTH = 6;
    // No 0/O or 1/I, so codes are easy to read out loud
    private static final String CODE_ALPHABET = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789";
    private static final long INVITE_LIFETIME_MS = 15 * 60 * 1000L;
    private final SecureRandom random = new SecureRandom();

    public interface OnJoinListener {
        void onResult(String error); // null on success
    }

    public interface OnLobbyChangedListener {
        void onChanged(Map<String, Object> lobby); // null once the lobby is deleted
    }

    public interface OnInviteListener {
        void onInvite(String inviteId, String fromName, String code);
    }

    private String randomLobbyCode() {
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < LOBBY_CODE_LENGTH; i++) {
            sb.append(CODE_ALPHABET.charAt(random.nextInt(CODE_ALPHABET.length())));
        }
        return sb.toString();
    }

    /**
     * Creates an open lobby with the host in slot 0 and returns its join code (null on failure).
     * Retries with a new code in the rare case the random one is already taken.
     */
    public void createLobby(String hostId, String hostName, OnStringResultListener listener) {
        String code = randomLobbyCode();
        DocumentReference ref = db.collection("lobbies").document(code);
        db.runTransaction(transaction -> {
            if (transaction.get(ref).exists()) return null;
            Map<String, Object> host = new HashMap<>();
            host.put("name", hostName);
            host.put("slot", 0);
            Map<String, Object> players = new HashMap<>();
            players.put(hostId, host);

            Map<String, Object> lobby = new HashMap<>();
            lobby.put("hostId",    hostId);
            lobby.put("status",    "open");
            lobby.put("seed",      0L);
            lobby.put("players",   players);
            lobby.put("createdAt", Timestamp.now());
            transaction.set(ref, lobby);
            return code;
        }).addOnSuccessListener(result -> {
            if (result != null) listener.onResult(result);
            else createLobby(hostId, hostName, listener);
        }).addOnFailureListener(e -> {
            Log.e(TAG, "createLobby failed", e);
            listener.onResult(null);
        });
    }

    /**
     * Joins an open lobby, taking the lowest free slot. Done in a transaction so two players
     * joining at once can't exceed the party size or share a slot.
     */
    @SuppressWarnings("unchecked")
    public void joinLobby(String code, String userId, String name, OnJoinListener listener) {
        DocumentReference ref = db.collection("lobbies").document(code);
        db.runTransaction(transaction -> {
            DocumentSnapshot snap = transaction.get(ref);
            if (!snap.exists()) return "No party found with that code";
            if (!"open".equals(snap.getString("status"))) return "That party already started";

            Map<String, Object> players = (Map<String, Object>) snap.get("players");
            if (players == null) players = new HashMap<>();
            if (players.containsKey(userId)) return null;
            if (players.size() >= MAX_PARTY_SIZE) return "That party is full";

            boolean[] taken = new boolean[MAX_PARTY_SIZE];
            for (Object entry : players.values()) {
                Object slot = ((Map<String, Object>) entry).get("slot");
                int s = slot != null ? ((Number) slot).intValue() : -1;
                if (s >= 0 && s < MAX_PARTY_SIZE) taken[s] = true;
            }
            int slot = 0;
            while (slot < MAX_PARTY_SIZE - 1 && taken[slot]) slot++;

            Map<String, Object> me = new HashMap<>();
            me.put("name", name);
            me.put("slot", slot);
            transaction.update(ref, FieldPath.of("players", userId), me);
            return null;
        }).addOnSuccessListener(listener::onResult)
          .addOnFailureListener(e -> {
              Log.e(TAG, "joinLobby failed", e);
              listener.onResult("Couldn't join the party");
          });
    }

    /** Live updates for a lobby; remove the returned registration when leaving the screen. */
    public ListenerRegistration listenToLobby(String code, OnLobbyChangedListener listener) {
        return db.collection("lobbies").document(code)
                .addSnapshotListener((snap, e) -> {
                    if (e != null) {
                        Log.e(TAG, "listenToLobby failed", e);
                        return;
                    }
                    listener.onChanged(snap != null && snap.exists() ? snap.getData() : null);
                });
    }

    /** A guest leaves: removes only their own entry. */
    public void leaveLobby(String code, String userId) {
        db.collection("lobbies").document(code)
                .update(FieldPath.of("players", userId), FieldValue.delete())
                .addOnFailureListener(e -> Log.e(TAG, "leaveLobby failed", e));
    }

    /** The host leaves: deletes the lobby, which every guest's listener sees as closed. */
    public void closeLobby(String code) {
        db.collection("lobbies").document(code)
                .delete()
                .addOnFailureListener(e -> Log.e(TAG, "closeLobby failed", e));
    }

    /** Host only: marks the run as started and shares the seed every phone will use. */
    public void startLobby(String code, long seed) {
        Map<String, Object> updates = new HashMap<>();
        updates.put("status", "started");
        updates.put("seed",   seed);
        db.collection("lobbies").document(code)
                .update(updates)
                .addOnFailureListener(e -> Log.e(TAG, "startLobby failed", e));
    }

    /** Invites a friend to the lobby; they see it as a pop-up on their main menu. */
    public void sendInvite(String fromId, String fromName, String toId, String code,
                           OnCompleteListener listener) {
        Map<String, Object> invite = new HashMap<>();
        invite.put("from",      fromId);
        invite.put("fromName",  fromName);
        invite.put("to",        toId);
        invite.put("code",      code);
        invite.put("createdAt", Timestamp.now());
        db.collection("invites")
                .add(invite)
                .addOnSuccessListener(ref -> listener.onComplete(true))
                .addOnFailureListener(e -> {
                    Log.e(TAG, "sendInvite failed", e);
                    listener.onComplete(false);
                });
    }

    /**
     * Live listener for invites sent to this user. Each new invite is reported once;
     * invites older than 15 minutes are deleted instead of shown.
     */
    public ListenerRegistration listenToInvites(String userId, OnInviteListener listener) {
        return db.collection("invites")
                .whereEqualTo("to", userId)
                .addSnapshotListener((query, e) -> {
                    if (e != null || query == null) {
                        if (e != null) Log.e(TAG, "listenToInvites failed", e);
                        return;
                    }
                    long now = System.currentTimeMillis();
                    for (DocumentChange change : query.getDocumentChanges()) {
                        if (change.getType() != DocumentChange.Type.ADDED) continue;
                        DocumentSnapshot doc = change.getDocument();
                        Timestamp created = doc.getTimestamp("createdAt");
                        if (created == null || now - created.toDate().getTime() > INVITE_LIFETIME_MS) {
                            deleteInvite(doc.getId());
                            continue;
                        }
                        listener.onInvite(doc.getId(), doc.getString("fromName"), doc.getString("code"));
                    }
                });
    }

    public void deleteInvite(String inviteId) {
        db.collection("invites").document(inviteId)
                .delete()
                .addOnFailureListener(e -> Log.e(TAG, "deleteInvite failed", e));
    }

    /**
     * Converts a Firestore player document to a LeaderboardItem.
     */
    private LeaderboardItem docToLeaderboardItem(DocumentSnapshot doc, int rank) {
        try {
            Map<String, Object> data = doc.getData();
            if (data == null) return null;

            String username      = data.get("username") != null
                    ? (String) data.get("username") : "Unknown";
            int highestFloor     = data.get("highestFloor") != null
                    ? ((Number) data.get("highestFloor")).intValue() : 0;
            int enemiesKilled    = data.get("enemiesKilled") != null
                    ? ((Number) data.get("enemiesKilled")).intValue() : 0;
            int bossesKilled     = data.get("bossesKilled") != null
                    ? ((Number) data.get("bossesKilled")).intValue() : 0;
            int timesDied        = data.get("timesDied") != null
                    ? ((Number) data.get("timesDied")).intValue() : 0;
            long playtimeSeconds = data.get("playtimeSeconds") != null
                    ? ((Number) data.get("playtimeSeconds")).longValue() : 0L;

            return new LeaderboardItem(doc.getId(), username, highestFloor,
                    enemiesKilled, bossesKilled, timesDied, playtimeSeconds, rank);
        } catch (Exception e) {
            return null;
        }
    }

